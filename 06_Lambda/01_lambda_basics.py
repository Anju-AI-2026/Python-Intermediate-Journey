# Q1: Square of a number
square = lambda num: num * num
print("Square:", square(2))


# Q2: Multiplication of two numbers
multi = lambda num1, num2: num1 * num2
print("Multiplication:", multi(2, 3))


# Q3: Subtraction of two numbers
sub = lambda num1, num2: num1 - num2
print("Subtraction:", sub(5, 2))


# Q4: Division of two numbers
divide = lambda num1, num2: num1 / num2
print("Division:", divide(10, 5))


# Q5: Double a number
double = lambda num: num + num
print("Double:", double(8))